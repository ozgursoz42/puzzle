export const TRANSLATIONS: Record<string, Partial<Translations>> = {
  ...BASE_TRANSLATIONS,
  ...MORE_TRANSLATIONS,
};

/**
 * Resolves translation with fallback chain:
 * exact lang -> regional alias -> base lang (e.g. "es-MX" -> "es") -> English ("en")
 */
export function getI18n(langId: string): Translations {
  const en = TRANSLATIONS.en as Translations;
  const baseCode = langId.split("-")[0];
  const custom =
    TRANSLATIONS[langId] ||
    (langId === "zh-HK" ? TRANSLATIONS["zh-TW"] : undefined) ||
    (langId === "sr-ME" ? TRANSLATIONS["sr"] : undefined) ||
    TRANSLATIONS[baseCode] ||
    {};
  return {
    ...en,
    ...custom,
    categories: {
      ...en.categories,
      ...(custom.categories || {}),
    },
  };
}
